# Test database URL — separate from the main el_contable DB to avoid conflicts
# Uses a unique name so parallel test runs don't clash.
TEST_DB_NAME = f"el_contable_test_migration_{uuid.uuid4().hex[:8]}"
TEST_DB_URL = f"postgresql+psycopg://el_contable:el_contable@localhost:5432/{TEST_DB_NAME}"
MAIN_DB_URL = "postgresql+psycopg://el_contable:el_contable@localhost:5432/el_contable"

# Revision identifiers from the migration chain
PREV_REVISION = "a1b2c3d4e5f6"  # add_orden_extracto — starting point for the test
TARGET_REVISION = "english_movements_schema"  # the migration under test


