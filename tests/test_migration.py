def test_upgrade_preserves_rows_and_generates_uuids(pg_db) -> None:
    """Upgrade from PREV_REVISION to TARGET_REVISION: rows preserved, UUIDs, FKs intact."""
    engine = pg_db["engine"]
    movement_rows, account_id, piggy_id = pg_db["seed_data"]

    # Apply the upgrade migration
    _run_migrations_on_db(TEST_DB_URL, TARGET_REVISION)

    # Connect and verify
    with engine.connect() as conn:
        # --- Rows preserved ---
        result = conn.execute(text("SELECT COUNT(*) FROM movements")).scalar_one()
        assert result == 3, f"Expected 3 movements, got {result}"

        result = conn.execute(text("SELECT COUNT(*) FROM movements_piggy_banks")).scalar_one()
        assert result == 1, f"Expected 1 movements_piggy_banks row, got {result}"

        # --- IDs are now UUIDs ---
        rows = conn.execute(text("SELECT id FROM movements ORDER BY order_statement")).fetchall()
        for row in rows:
            val = row[0]
            assert isinstance(val, uuid.UUID), f"Expected UUID, got {type(val)}: {val}"

        # --- account_id preserved ---
        result = conn.execute(
            text("SELECT COUNT(*) FROM movements WHERE account_id = :aid"), {"aid": str(account_id)}
        ).scalar_one()
        assert result == 3

        # --- FK in movements_piggy_banks still valid ---
        result = conn.execute(
            text("SELECT movement_id FROM movements_piggy_banks WHERE piggy_bank_id = :pid"),
            {"pid": str(piggy_id)},
        ).scalar_one()
        assert isinstance(result, uuid.UUID), f"FK movement_id should be UUID, got {type(result)}"

        # --- movement_date is Date (not DateTime) ---
        md_row = conn.execute(text("SELECT movement_date FROM movements LIMIT 1")).fetchone()
        assert isinstance(md_row[0], date), f"movement_date should be date, got {type(md_row[0])}"

        # --- expires_at column is gone ---
        cols = conn.execute(
            text(
                "SELECT column_name FROM information_schema.columns WHERE table_name = 'movements'"
            )
        ).fetchall()
        col_names = [r[0] for r in cols]
        assert "expires_at" not in col_names

        # --- English column names exist ---
        for col in (
            "movement_date",
            "concept",
            "amount",
            "type",
            "available_balance",
            "order_statement",
        ):
            assert col in col_names, f"Missing English column: {col}"

        # --- Spanish column names are gone ---
        for col in ("fecha_movimiento", "concepto", "importe", "disponible"):
            assert col not in col_names, f"Stale Spanish column still present: {col}"

        # --- Unique constraint on (account_id, order_statement) exists ---
        constraints = conn.execute(
            text(
                "SELECT constraint_name FROM information_schema.table_constraints "
                "WHERE table_name = 'movements' AND constraint_type = 'UNIQUE'"
            )
        ).fetchall()
        constraint_names = [r[0] for r in constraints]
        assert "uq_movements_account_order_statement" in constraint_names


def test_downgrade_regenerates_sequential_bigint_ids(pg_db) -> None:
    """Downgrade from TARGET_REVISION back to PREV_REVISION:
    sequential bigint ids regenerated by order_statement, no dangling FKs."""
    engine = pg_db["engine"]
    movement_rows, account_id, piggy_id = pg_db["seed_data"]

    # First apply the upgrade so we can downgrade from it
    _run_migrations_on_db(TEST_DB_URL, TARGET_REVISION)

    # Now downgrade (must use downgrade command, not upgrade)
    _run_migration_downgrade(TEST_DB_URL, PREV_REVISION)

    with engine.connect() as conn:
        # --- All 3 movements still present ---
        result = conn.execute(text("SELECT COUNT(*) FROM movements")).scalar_one()
        assert result == 3

        # --- movements_piggy_banks row still present (FK preserved) ---
        result = conn.execute(text("SELECT COUNT(*) FROM movements_piggy_banks")).scalar_one()
        assert result == 1

        # --- IDs are now bigint (sequential, regenerated by orden_extracto) ---
        rows = conn.execute(
            text("SELECT id, orden_extracto FROM movements ORDER BY orden_extracto")
        ).fetchall()
        ids = [row[0] for row in rows]
        ordinals = [row[1] for row in rows]

        for id_val in ids:
            assert isinstance(id_val, int), f"Expected bigint id, got {type(id_val)}: {id_val}"

        # IDs are 1-based sequential integers matching orden_extracto
        assert ids == sorted(ids), f"IDs should be sequential: {ids}"
        assert ids == ordinals, f"IDs {ids} should match orden_extracto {ordinals}"

        # --- FK in movements_piggy_banks still valid (references a bigint id) ---
        fk_val = conn.execute(
            text("SELECT movement_id FROM movements_piggy_banks LIMIT 1")
        ).scalar_one()
        assert isinstance(fk_val, int), (
            f"Downgraded FK movement_id should be int, got {type(fk_val)}"
        )

        # --- Spanish columns restored ---
        cols = conn.execute(
            text(
                "SELECT column_name FROM information_schema.columns WHERE table_name = 'movements'"
            )
        ).fetchall()
        col_names = [r[0] for r in cols]
        for col in ("fecha_movimiento", "concepto", "importe", "disponible", "orden_extracto"):
            assert col in col_names, f"Spanish column missing after downgrade: {col}"

        # --- expires_at restored ---
        assert "expires_at" in col_names

        # --- English columns gone ---
        for col in ("movement_date", "concept", "amount"):
            assert col not in col_names, f"Stale English column after downgrade: {col}"
