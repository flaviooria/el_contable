def _pg_url_for_db(db_name: str) -> str:
    """Return a PostgreSQL connection URL pointing at the given database name."""
    return f"postgresql+psycopg://el_contable:el_contable@localhost:5432/{db_name}"


def _create_test_db(pg_url: str) -> None:
    """Create the test database if it does not already exist."""
    admin_url = _pg_url_for_db("postgres")
    eng = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with eng.connect() as conn:
        conn.execute(
            text(f"SELECT 1 FROM pg_database WHERE datname = '{TEST_DB_NAME}'"),
        )
        exists = conn.execute(
            text(f"SELECT 1 FROM pg_database WHERE datname = '{TEST_DB_NAME}'"),
        ).fetchone()
        if not exists:
            conn.execute(text(f"CREATE DATABASE {TEST_DB_NAME}"))
    eng.dispose()


def _drop_test_db(pg_url: str) -> None:
    """Drop the test database if it exists."""
    admin_url = _pg_url_for_db("postgres")
    eng = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with eng.connect() as conn:
        conn.execute(text(f"DROP DATABASE IF EXISTS {TEST_DB_NAME}"))
    eng.dispose()


def _run_migrations_on_db(db_url: str, rev: str | None) -> None:
    """Run alembic upgrade to the given revision on the given database URL.

    alembic.ini is read from the project root to find migration scripts.
    We override sqlalchemy.url so we can target any database.
    """
    cfg = alembic_config.Config(Path(__file__).resolve().parents[1] / "alembic.ini")
    cfg.set_main_option("sqlalchemy.url", db_url)

    if rev is None:
        # Stamp as up-to-date (no migration run)
        command.stamp(cfg, "head")
    else:
        # Run all migrations up to and including `rev`
        command.upgrade(cfg, rev)


def _run_migration_downgrade(db_url: str, rev: str | None) -> None:
    """Run alembic downgrade to the given revision on the given database URL.

    Used when the test needs to move to an older revision (e.g. PREV_REVISION
    after having upgraded to TARGET_REVISION).
    """
    cfg = alembic_config.Config(Path(__file__).resolve().parents[1] / "alembic.ini")
    cfg.set_main_option("sqlalchemy.url", db_url)

    if rev is None:
        command.stamp(cfg, "head")
    else:
        command.downgrade(cfg, rev)


def _seed_spanish_schema(db_conn: Connection) -> list[dict]:
    """Insert movements and movements_piggy_banks rows in the pre-migration schema.

    Returns the list of inserted movement dicts (with Spanish column names).
    """
    # Insert an account first (movements needs account_id FK)
    account_id = uuid.uuid4()
    db_conn.execute(
        text(
            "INSERT INTO accounts (id, base_balance, entry_date) "
            "VALUES (:id, :base_balance, :entry_date)"
        ),
        {"id": str(account_id), "base_balance": 5000.0, "entry_date": date(2024, 1, 1)},
    )

    # Insert a piggy bank linked to the account
    # At PREV_REVISION (a1b2c3d4e5f6), piggy_banks columns are already English
    # (renamed in 4ede7a986064 before this revision):
    # name, max_balance (no 'balance' column at this point)
    piggy_id = uuid.uuid4()
    db_conn.execute(
        text(
            "INSERT INTO piggy_banks (id, account_id, name, max_balance) "
            "VALUES (:id, :account_id, :name, :max_balance)"
        ),
        {"id": str(piggy_id), "account_id": str(account_id), "name": " Piggy", "max_balance": 0.0},
    )

    # Insert movements with the Spanish schema (fecha_movimiento, concepto, importe, ...)
    # At PREV_REVISION, movements.id is INTEGER (bigint), not UUID.
    # Use sequential integers; UUIDs are assigned during the english_movements_schema upgrade.
    movement_data = [
        {
            "id": 1,
            "account_id": account_id,
            "fecha_movimiento": date(2024, 1, 1),
            "concepto": "Nómina January",
            "importe": 3000.0,
            "tipo": "INGRESO",
            "disponible": 3000.0,
            "orden_extracto": 1,
            "expires_at": datetime(2025, 1, 1, tzinfo=timezone.utc),
        },
        {
            "id": 2,
            "account_id": account_id,
            "fecha_movimiento": date(2024, 1, 15),
            "concepto": "Freelance",
            "importe": 500.0,
            "tipo": "INGRESO",
            "disponible": 3500.0,
            "orden_extracto": 2,
            "expires_at": datetime(2025, 1, 1, tzinfo=timezone.utc),
        },
        {
            "id": 3,
            "account_id": account_id,
            "fecha_movimiento": date(2024, 2, 1),
            "concepto": "Nómina February",
            "importe": 3000.0,
            "tipo": "INGRESO",
            "disponible": 6500.0,
            "orden_extracto": 3,
            "expires_at": datetime(2025, 1, 1, tzinfo=timezone.utc),
        },
    ]

    inserted_ids = []
    for m in movement_data:
        db_conn.execute(
            text(
                "INSERT INTO movements "
                "(id, account_id, fecha_movimiento, concepto, importe, tipo, disponible, orden_extracto, expires_at) "
                "VALUES (:id, :account_id, :fecha_movimiento, :concepto, :importe, :tipo, :disponible, :orden_extracto, :expires_at)"
            ),
            {
                "id": m["id"],
                "account_id": str(m["account_id"]),
                "fecha_movimiento": m["fecha_movimiento"],
                "concepto": m["concepto"],
                "importe": m["importe"],
                "tipo": m["tipo"],
                "disponible": m["disponible"],
                "orden_extracto": m["orden_extracto"],
                "expires_at": m["expires_at"],
            },
        )
        inserted_ids.append(m)

    # Link first movement to piggy bank
    # At PREV_REVISION, movements_piggy_banks.movement_id is INTEGER FK.
    db_conn.execute(
        text(
            "INSERT INTO movements_piggy_banks (movement_id, piggy_bank_id) "
            "VALUES (:movement_id, :piggy_bank_id)"
        ),
        {"movement_id": inserted_ids[0]["id"], "piggy_bank_id": str(piggy_id)},
    )

    db_conn.commit()
    return inserted_ids, account_id, piggy_id


